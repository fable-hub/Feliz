[<AutoOpen>]
module ReactTypes =

    type ReactNode = U6<ReactElement, seq<ReactElement>, string, float, int, bool>

    type UseSyncExternalStoreSubscribe = delegate of (unit -> unit) -> (unit -> unit)
    type UseSyncExternalStoreSnapshot<'T> = delegate of unit -> 'T

    [<Erase>]
    type IReactRoot =
        /// Renders the provided React element into the DOM in the supplied container.
        abstract render: ReactElement -> unit
        /// Removes a mounted React component from the DOM and cleans up its event handlers and state.
        abstract unmount: unit -> unit

    type ReactContext<'a> = interface end

    /// Additional information React passes along with an error it caught.
    type ReactErrorInfo =
        /// The component stack at the moment the error was thrown.
        abstract componentStack: string

    /// Options for `ReactDOM.createRoot` and `ReactDOM.hydrateRoot`.
    ///
    /// - `identifierPrefix`: prefix for the IDs generated by `React.useId`. Avoids conflicts between multiple roots on one page.
    /// - `onCaughtError`: called when React catches an error in an error boundary.
    /// - `onUncaughtError`: called when an error is thrown and not caught by any error boundary.
    /// - `onRecoverableError`: called when React automatically recovers from an error, e.g. a hydration mismatch.
    ///
    /// ```fsharp
    /// ReactDOM.createRoot(
    ///     document.getElementById "root",
    ///     RootOptions(onUncaughtError = fun error info -> reportError error info.componentStack)
    /// )
    /// ```
    [<AllowNullLiteral; Global>]
    type RootOptions
        [<ParamObject; Emit("$0")>]
        (
            ?identifierPrefix: string,
            ?onCaughtError: exn -> ReactErrorInfo -> unit,
            ?onUncaughtError: exn -> ReactErrorInfo -> unit,
            ?onRecoverableError: exn -> ReactErrorInfo -> unit
        ) = class end

    /// The object returned by `ReactDOMServer.renderToPipeableStream`.
    type PipeableStream =
        /// Pipes the HTML into the provided Node.js Writable stream. Call it in `onShellReady` (streaming) or `onAllReady` (crawlers, static generation).
        abstract pipe: destination: obj -> obj
        /// Stops server rendering; remaining content is rendered on the client.
        abstract abort: ?reason: obj -> unit

    /// Visibility mode of a `React.Activity` boundary.
    [<StringEnum; RequireQualifiedAccess>]
    type ActivityMode =
        /// Children are visible and their effects are mounted.
        | Visible
        /// Children are hidden with `display: none`, their effects are cleaned up and updates are deferred.
        /// State is preserved.
        | Hidden

    /// Timing information passed to the `onRender` callback of `React.Profiler`.
    type ProfilerRenderInfo =
        /// The `id` of the Profiler tree that has just committed.
        abstract id: string
        /// "mount", "update" or "nested-update".
        abstract phase: string
        /// Milliseconds spent rendering the Profiler and its descendants for the current update.
        abstract actualDuration: float
        /// Estimated milliseconds it would take to re-render the whole subtree without any memoization.
        abstract baseDuration: float
        /// Timestamp of when React began rendering the current update.
        abstract startTime: float
        /// Timestamp of when React committed the current update.
        abstract commitTime: float

    /// Passed to the fallback render function of `React.ErrorBoundary`.
    type ErrorBoundaryFallbackProps =
        /// The error that was caught. Usually a JavaScript `Error`, but anything can be thrown in JavaScript.
        abstract error: exn
        /// Clears the error and renders the children again.
        abstract reset: unit -> unit

    /// Returned by `ReactDOM.useFormStatus`: status of the last submission of the parent `<form>`.
    type FormStatus =
        /// `true` while the parent form is submitting.
        abstract pending: bool
        /// The data the parent form is submitting, `None` when there is no active submission.
        abstract data: FormData option
        /// "get" or "post".
        abstract ``method``: string
        /// The function or URL passed to the parent form's `action` prop, `None` when there is no parent form.
        abstract action: obj option

    /// The instance a ref on `React.Fragment` receives. It lets you work with the first-level DOM children of the
    /// Fragment as a group, without a wrapper element. Requires React 19.3 or later.
    [<AllowNullLiteral>]
    type FragmentInstance =
        /// Adds an event listener to each first-level DOM child.
        abstract addEventListener:
            ``type``: string * listener: (Event -> unit) * ?options: AddEventListenerOptions -> unit

        /// Removes an event listener from each first-level DOM child.
        abstract removeEventListener: ``type``: string * listener: (Event -> unit) * ?options: obj -> unit
        /// Dispatches an event on the Fragment's parent. Returns `false` if the event was cancelled.
        abstract dispatchEvent: event: Event -> bool
        /// Focuses the first focusable DOM node in the Fragment (depth-first).
        abstract focus: ?options: obj -> unit
        /// Focuses the last focusable DOM node in the Fragment (depth-first, in reverse).
        abstract focusLast: ?options: obj -> unit
        /// Removes focus if the active element is inside the Fragment.
        abstract blur: unit -> unit
        /// Starts observing each first-level DOM child with an `IntersectionObserver` or `ResizeObserver`.
        abstract observeUsing: observer: obj -> unit
        /// Stops observing the first-level DOM children with the given observer.
        abstract unobserveUsing: observer: obj -> unit
        /// The bounding rectangles of all first-level DOM children.
        abstract getClientRects: unit -> ClientRect[]
        /// The root node (document or shadow root) containing the Fragment's parent.
        abstract getRootNode: ?options: obj -> obj
        /// Compares the position of a node with the Fragment, like `Node.compareDocumentPosition`.
        abstract compareDocumentPosition: otherNode: Node -> int
        /// Scrolls the Fragment's first (or, with `false`, last) DOM child into view.
        abstract scrollIntoView: ?alignToTop: bool -> unit

    /// A `::view-transition-*` pseudo-element. Use `animate` to run a custom Web Animation on it.
    type ViewTransitionPseudoElement =
        /// Runs a Web Animation on the pseudo-element, like `Element.animate`. Returns the `Animation`.
        abstract animate: keyframes: obj * ?options: obj -> obj
        /// The animations currently running on the pseudo-element.
        abstract getAnimations: unit -> obj[]

    /// Passed to the `onEnter`, `onExit`, `onUpdate` and `onShare` callbacks of `React.ViewTransition`.
    type ViewTransitionInstance =
        /// The `view-transition-name` of this boundary.
        abstract name: string
        /// `::view-transition-group(name)`
        abstract group: ViewTransitionPseudoElement
        /// `::view-transition-image-pair(name)`
        abstract imagePair: ViewTransitionPseudoElement
        /// `::view-transition-old(name)`, a snapshot of the element before the transition.
        abstract old: ViewTransitionPseudoElement
        /// `::view-transition-new(name)`, the live element after the transition.
        abstract ``new``: ViewTransitionPseudoElement

    /// A property of `React.ViewTransition`. Create it with the `viewTransition` helpers.
    type IViewTransitionProperty = interface end
